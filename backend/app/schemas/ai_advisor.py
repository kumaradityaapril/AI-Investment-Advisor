from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

ADVISOR_DISCLAIMER = (
    "This analysis is for educational purposes only and is not "
    "personalized investment advice. Investment decisions involve "
    "risk, including possible loss of capital. Consult a qualified "
    "financial professional before making investment decisions."
)


class AIAdvisorRequest(BaseModel):
    """Request submitted by an investor to the AI Advisor."""

    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        min_length=3,
        max_length=2000,
        description="The investor's financial question.",
    )

    @field_validator("question")
    @classmethod
    def validate_question(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("Question cannot be empty.")

        return value


class AdvisorRecommendation(BaseModel):
    """One actionable recommendation generated by the AI Advisor."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=3, max_length=150)
    explanation: str = Field(min_length=10, max_length=1500)
    suggested_action: str = Field(min_length=5, max_length=1000)
    priority: Literal["low", "medium", "high"]


class AdvisorEvidence(BaseModel):
    """A reference to a retrieved financial document chunk."""

    model_config = ConfigDict(extra="forbid")

    chunk_id: int = Field(gt=0)
    document_id: int = Field(gt=0)
    filename: str = Field(min_length=1, max_length=255)
    page_number: int = Field(gt=0)
    supporting_excerpt: str = Field(min_length=1, max_length=1000)


class FinancialClaim(BaseModel):
    model_config = ConfigDict(extra="forbid")

    metric_key: Literal[
        "monthly_surplus",
        "annual_income",
        "annual_expenses",
        "savings_rate_percent",
        "expense_ratio_percent",
        "required_monthly_contribution",
        "planned_monthly_investment",
        "monthly_contribution_shortfall",
    ]
    claimed_value: Decimal
    goal_id: int | None = Field(default=None, gt=0)

    @field_validator("claimed_value")
    @classmethod
    def validate_claimed_value(cls, value: Decimal) -> Decimal:
        if not value.is_finite():
            raise ValueError("Financial claim must be finite")
        return value

    @model_validator(mode="after")
    def validate_goal_reference(self):
        goal_metrics = {
            "required_monthly_contribution",
            "planned_monthly_investment",
            "monthly_contribution_shortfall",
        }
        if self.metric_key in goal_metrics and self.goal_id is None:
            raise ValueError("Goal-specific claims require a goal_id")
        if self.metric_key not in goal_metrics and self.goal_id is not None:
            raise ValueError("goal_id is only valid for goal-specific claims")
        return self


class AIAdvisorGenerationResponse(BaseModel):
    """Structured response produced by Gemini containing analysis and evidence chunk IDs."""

    model_config = ConfigDict(extra="forbid")

    overall_assessment: str = Field(min_length=10, max_length=2000)

    key_findings: list[str] = Field(min_length=1, max_length=10)

    recommendations: list[AdvisorRecommendation] = Field(
        min_length=1,
        max_length=10,
    )

    risk_considerations: list[str] = Field(default_factory=list, max_length=10)

    assumptions: list[str] = Field(default_factory=list, max_length=10)

    limitations: list[str] = Field(min_length=1, max_length=10)

    evidence_chunk_ids: list[int] = Field(default_factory=list, max_length=5)

    financial_claims: list[FinancialClaim] = Field(
        default_factory=list,
        max_length=20,
    )

    @field_validator("evidence_chunk_ids")
    @classmethod
    def validate_evidence_chunk_ids(cls, v: list[int]) -> list[int]:
        if len(v) != len(set(v)):
            raise ValueError("Duplicate evidence chunk IDs are not permitted.")

        for chunk_id in v:
            if chunk_id <= 0:
                raise ValueError("Evidence chunk IDs must be positive integers.")

        return v


class AIAdvisorResponse(BaseModel):
    """Structured response returned by the AI Advisor after backend evidence assembly."""

    model_config = ConfigDict(extra="forbid")

    overall_assessment: str = Field(min_length=10, max_length=2000)

    key_findings: list[str] = Field(min_length=1, max_length=10)

    recommendations: list[AdvisorRecommendation] = Field(
        min_length=1,
        max_length=10,
    )

    risk_considerations: list[str] = Field(default_factory=list, max_length=10)

    assumptions: list[str] = Field(default_factory=list, max_length=10)

    limitations: list[str] = Field(min_length=1, max_length=10)

    evidence: list[AdvisorEvidence] = Field(default_factory=list, max_length=5)

    disclaimer: Literal[ADVISOR_DISCLAIMER] = ADVISOR_DISCLAIMER
